// Command gen regenerates the syscall-number and errno tables in
// crates/abi/src from golang.org/x/sys/unix, whose z*_linux_*.go files are
// themselves generated from the Linux UAPI headers (asm/unistd.h,
// asm-generic/errno*.h).
//
// Usage (from this directory):
//
//	go run gen.go -xsys $(go env GOMODCACHE)/golang.org/x/sys@v0.48.0/unix -out ../src
package main

import (
	"bufio"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strconv"
	"strings"
)

type entry struct {
	name string
	val  int64
}

// extraErrno lists errno values from newer Linux UAPI headers than the
// x/sys release in use.
var extraErrno = []struct {
	name string
	val  int64
	desc string
}{
	{"EFTYPE", 134, "wrong file type for the intended operation"}, // Linux 7.2 asm-generic/errno.h
}

var (
	sysRe   = regexp.MustCompile(`^\s+SYS_([A-Z0-9_]+)\s+=\s+(\d+)`)
	errnoRe = regexp.MustCompile(`^\s+(E[A-Z0-9]+)\s+=\s+syscall\.Errno\((0x[0-9a-f]+)\)`)
	descRe  = regexp.MustCompile(`^\s+\{\s*(\d+),\s*"(E[A-Z0-9]+)",\s*"([^"]*)"\s*\},`)
)

func scan(path string, re *regexp.Regexp) []entry {
	f, err := os.Open(path)
	if err != nil {
		panic(err)
	}
	defer f.Close()
	var out []entry
	s := bufio.NewScanner(f)
	for s.Scan() {
		m := re.FindStringSubmatch(s.Text())
		if m == nil {
			continue
		}
		v, err := strconv.ParseInt(m[2], 0, 64)
		if err != nil {
			panic(err)
		}
		out = append(out, entry{m[1], v})
	}
	return out
}

func main() {
	xsys := flag.String("xsys", "", "path to golang.org/x/sys/unix")
	out := flag.String("out", "../src", "output directory")
	flag.Parse()
	if *xsys == "" {
		fmt.Fprintln(os.Stderr, "-xsys required")
		os.Exit(2)
	}
	src := filepath.Base(filepath.Dir(*xsys))

	for _, a := range []struct{ goarch, dir string }{{"amd64", "x86_64"}, {"arm64", "aarch64"}} {
		ents := scan(filepath.Join(*xsys, "zsysnum_linux_"+a.goarch+".go"), sysRe)
		// __NR_arch_specific_syscall (arm64 244) is the base of a reserved
		// range, not a syscall; current UAPI headers no longer define it
		// (checked by layout_check.rs).
		kept := ents[:0]
		for _, e := range ents {
			if e.name != "ARCH_SPECIFIC_SYSCALL" {
				kept = append(kept, e)
			}
		}
		ents = kept
		sort.SliceStable(ents, func(i, j int) bool { return ents[i].val < ents[j].val })
		var b strings.Builder
		fmt.Fprintf(&b, "// @generated by crates/abi/gen/gen.go from %s zsysnum_linux_%s.go.\n", src, a.goarch)
		fmt.Fprintf(&b, "// Source of truth: Linux arch/%s syscall table (asm/unistd.h). DO NOT EDIT.\n\n", map[string]string{"amd64": "x86", "arm64": "arm64"}[a.goarch])
		b.WriteString("#![allow(missing_docs)]\n\n")
		for _, e := range ents {
			fmt.Fprintf(&b, "pub const %s: usize = %d;\n", e.name, e.val)
		}
		b.WriteString("\n/// `(number, name)` for every syscall in the table, sorted by number.\n")
		b.WriteString("/// Aliases (same number, second name) are listed after the primary name.\n")
		b.WriteString("pub const TABLE: &[(usize, &str)] = &[\n")
		for _, e := range ents {
			fmt.Fprintf(&b, "    (%d, %q),\n", e.val, strings.ToLower(e.name))
		}
		b.WriteString("];\n")
		write(filepath.Join(*out, a.dir, "nr.rs"), b.String())
	}

	// errno: identical on x86_64 and arm64 (both asm-generic/errno.h); verify.
	common := scan(filepath.Join(*xsys, "zerrors_linux.go"), errnoRe)
	e64 := append(scan(filepath.Join(*xsys, "zerrors_linux_amd64.go"), errnoRe), common...)
	ea64 := append(scan(filepath.Join(*xsys, "zerrors_linux_arm64.go"), errnoRe), common...)
	// Errnos newer than x/sys (checked against the UAPI headers by
	// layout_check.rs).
	for _, x := range extraErrno {
		e64 = append(e64, entry{x.name, x.val})
		ea64 = append(ea64, entry{x.name, x.val})
	}
	descs := map[int64]string{}
	primary := map[int64]string{95: "EOPNOTSUPP"}
	{
		f, _ := os.Open(filepath.Join(*xsys, "zerrors_linux_amd64.go"))
		s := bufio.NewScanner(f)
		for s.Scan() {
			if m := descRe.FindStringSubmatch(s.Text()); m != nil {
				v, _ := strconv.ParseInt(m[1], 10, 64)
				descs[v] = m[3]
				if _, ok := primary[v]; !ok {
					primary[v] = m[2]
				}
			}
		}
		f.Close()
	}
	for _, x := range extraErrno {
		descs[x.val] = x.desc
		primary[x.val] = x.name
	}
	sort.SliceStable(ea64, func(i, j int) bool { return ea64[i].name < ea64[j].name })
	sort.SliceStable(e64, func(i, j int) bool { return e64[i].name < e64[j].name })
	if fmt.Sprint(e64) != fmt.Sprint(ea64) {
		panic("errno differs between amd64 and arm64")
	}
	sort.SliceStable(e64, func(i, j int) bool {
		if e64[i].val != e64[j].val {
			return e64[i].val < e64[j].val
		}
		return e64[i].name < e64[j].name
	})
	var b strings.Builder
	fmt.Fprintf(&b, "// @generated by crates/abi/gen/gen.go from %s zerrors_linux_{amd64,arm64}.go.\n", src)
	b.WriteString("// Source of truth: Linux include/uapi/asm-generic/errno{,-base}.h (same on x86_64 and arm64). DO NOT EDIT.\n\n")
	for _, e := range e64 {
		if d, ok := descs[e.val]; ok && primary[e.val] == e.name {
			fmt.Fprintf(&b, "/// %s\n", d)
		}
		if primary[e.val] != e.name {
			fmt.Fprintf(&b, "/// Alias of %s.\n", primary[e.val])
		}
		fmt.Fprintf(&b, "pub const %s: i32 = %d;\n", e.name, e.val)
	}
	b.WriteString("\n/// Primary symbolic name for an errno value (first name wins for aliases).\n")
	b.WriteString("pub const fn name(e: i32) -> Option<&'static str> {\n    match e {\n")
	var nums []int64
	for v := range primary {
		nums = append(nums, v)
	}
	sort.Slice(nums, func(i, j int) bool { return nums[i] < nums[j] })
	for _, v := range nums {
		fmt.Fprintf(&b, "        %d => Some(%q),\n", v, primary[v])
	}
	b.WriteString("        _ => None,\n    }\n}\n")
	write(filepath.Join(*out, "errno_gen.rs"), b.String())
}

func write(path, s string) {
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		panic(err)
	}
	if err := os.WriteFile(path, []byte(s), 0o644); err != nil {
		panic(err)
	}
	fmt.Println("wrote", path)
}
