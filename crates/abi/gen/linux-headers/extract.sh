#!/bin/sh
# Regenerate crates/abi/src/linux_expected.rs from Linux UAPI headers.
#
#   inc=$(gen/linux-headers/fetch-headers.sh "$(mktemp -d)")
#   gen/linux-headers/extract.sh "$inc"
#
# For each of x86_64 and aarch64, compiles layout.c (plus a generated list of
# every __NR_* and E* macro) with `clang --target=<arch>-linux-gnu -nostdinc
# -S` against <inc> and <inc>/<arch>-linux-gnu, then scrapes the "@@ key value"
# lines the inline asm left in the assembly. Nothing is linked or executed,
# so any clang with the x86 and AArch64 backends works (Xcode's does).
set -eu

inc=${1:?usage: extract.sh <usr/include dir> [output.rs]}
here=$(cd "$(dirname "$0")" && pwd)
out=${2:-$(cd "$here/../../src" && pwd)/linux_expected.rs}
CC=${CC:-clang}

tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

emit_table() { # arch triplet RUSTNAME
	arch=$1
	triplet=$2
	set -- --target="$triplet" -nostdinc -ffreestanding -w -O0 \
		-I "$inc/$triplet" -I "$inc" -I "$here" -I "$here/stub"
	# Every syscall number and errno the headers define.
	printf '#include <asm/unistd.h>\n' | "$CC" "$@" -E -dM -x c - |
		awk '$1 == "#define" && $2 ~ /^__NR_/ && $2 != "__NR_syscalls" { print $2 }' |
		sort -u >"$tmp/nr.$arch"
	printf '#include <linux/errno.h>\n' | "$CC" "$@" -E -dM -x c - |
		awk '$1 == "#define" && $2 ~ /^E[A-Z0-9]+$/ { print $2 }' |
		sort -u >"$tmp/errno.$arch"
	{
		printf '#include "layout.c"\nvoid generated(void)\n{\n'
		sed 's/^__NR_\(.*\)$/\tV("nr.\1", __NR_\1);/' "$tmp/nr.$arch"
		sed 's/^\(.*\)$/\tV("errno.\1", \1);/' "$tmp/errno.$arch"
		printf '}\n'
	} >"$tmp/gen.$arch.c"
	"$CC" "$@" -S -o "$tmp/gen.$arch.s" "$tmp/gen.$arch.c"
	# .ascii "@@ key value\n"  (value may carry a $ or # immediate prefix)
	sed -n 's/.*"@@ \([^ ]*\) [$#]*\(-\{0,1\}[0-9][0-9]*\)\\n".*/\1 \2/p' "$tmp/gen.$arch.s" \
		>"$tmp/vals.$arch"
	n=$(wc -l <"$tmp/vals.$arch")
	if [ "$n" -lt 500 ]; then
		echo "extract.sh: only $n values for $arch; asm format changed?" >&2
		exit 1
	fi
}

emit_table x86_64 x86_64-linux-gnu
emit_table aarch64 aarch64-linux-gnu

ver=$(awk '$1 == "LINUX_VERSION_MAJOR" { a = $2 } $1 == "LINUX_VERSION_PATCHLEVEL" { b = $2 }
	$1 == "LINUX_VERSION_SUBLEVEL" { c = $2 } END { print a "." b "." c }' "$tmp/vals.x86_64")

{
	echo "// @generated by crates/abi/gen/linux-headers/extract.sh from the Linux $ver UAPI"
	echo "// headers (Debian linux-libc-dev) and kinternal.h. DO NOT EDIT; rerun the script."
	echo "//"
	echo "// (key, value): \"<struct>.__size\", \"<struct>.__align\", \"<struct>.<field>\""
	echo "// (offsetof), \"<MACRO>\", \"nr.<syscall>\", \"errno.<NAME>\"."
	echo
	echo "/// Kernel version the values were extracted from."
	echo "pub const LINUX_VERSION: &str = \"$ver\";"
	for arch in x86_64 aarch64; do
		upper=$(echo "$arch" | tr a-z A-Z)
		echo
		echo "/// Values for $arch."
		echo "pub static $upper: &[(&str, i64)] = &["
		awk '{ printf "    (\"%s\", %s),\n", $1, $2 }' "$tmp/vals.$arch"
		echo "];"
	done
} >"$out"
echo "wrote $out (Linux $ver)" >&2
